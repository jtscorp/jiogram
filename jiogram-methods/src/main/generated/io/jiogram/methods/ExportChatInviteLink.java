package io.jiogram.methods;

import com.fasterxml.jackson.annotation.JsonAutoDetect;
import com.fasterxml.jackson.annotation.JsonAutoDetect.Visibility;
import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonProperty;
import io.jiogram.types.ChatId;
import io.jiogram.types.TelegramMethod;
import java.util.Objects;

/**
 * Use this method to generate a new primary invite link for a chat; any previously generated
 * primary link is revoked. The bot must be an administrator in the chat for this to work and must
 * have the appropriate administrator rights. Returns the new invite link as String on success.
 * <br>Note: Each administrator in a chat generates their own invite links. Bots can't use invite
 * links generated by other administrators. If you want your bot to work with invite links, it will
 * need to generate its own link using exportChatInviteLink or by calling the getChat method. If
 * your bot needs to generate a new primary invite link replacing its previous one, use
 * exportChatInviteLink again.
 *
 * @see <a href="https://core.telegram.org/bots/api#exportchatinvitelink">exportChatInviteLink in the Bot API</a>
 */
@JsonAutoDetect(getterVisibility = Visibility.NONE, isGetterVisibility = Visibility.NONE)
public final class ExportChatInviteLink implements TelegramMethod<String> {

    @JsonProperty("chat_id")
    private final ChatId chatId;

    /**
     * Creates a new {@code ExportChatInviteLink} instance.
     *
     * @param chatId Unique identifier for the target chat or username of the target channel (in the
     *     format &#64;channelusername)
     */
    @JsonCreator
    public ExportChatInviteLink(
            @JsonProperty("chat_id") ChatId chatId) {
        this.chatId = chatId;
    }

    @Override
    public String apiMethod() {
        return "exportChatInviteLink";
    }

    @Override
    public String apiReturnType() {
        return "String";
    }

    /**
     * Unique identifier for the target chat or username of the target channel (in the format
     * &#64;channelusername)
     */
    public ChatId chatId() {
        return chatId;
    }

    public ExportChatInviteLink withChatId(ChatId chatId) {
        return new ExportChatInviteLink(chatId);
    }

    @Override
    public boolean equals(Object o) {
        if (this == o) {
            return true;
        }
        if (!(o instanceof ExportChatInviteLink)) {
            return false;
        }
        ExportChatInviteLink that = (ExportChatInviteLink) o;
        return Objects.equals(this.chatId, that.chatId);
    }

    @Override
    public int hashCode() {
        return Objects.hash(this.chatId);
    }

    @Override
    public String toString() {
        return "ExportChatInviteLink[chatId=" + this.chatId
                + "]";
    }
}
